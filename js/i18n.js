(function () {
  function resolve(dict, key) {
    return key.split(".").reduce(function (o, k) { return o && o[k]; }, dict);
  }

  function applyLanguage(lang) {
    var dict = window.I18N[lang] || window.I18N.en;
    document.documentElement.setAttribute("lang", lang);

    document.querySelectorAll("[data-i18n]").forEach(function (el) {
      var val = resolve(dict, el.getAttribute("data-i18n"));
      if (val != null) el.textContent = val;
    });
    document.querySelectorAll("[data-i18n-html]").forEach(function (el) {
      var val = resolve(dict, el.getAttribute("data-i18n-html"));
      if (val != null) el.innerHTML = val;
    });
    document.querySelectorAll("[data-i18n-placeholder]").forEach(function (el) {
      var val = resolve(dict, el.getAttribute("data-i18n-placeholder"));
      if (val != null) el.setAttribute("placeholder", val);
    });
    document.querySelectorAll("[data-i18n-aria]").forEach(function (el) {
      var val = resolve(dict, el.getAttribute("data-i18n-aria"));
      if (val != null) el.setAttribute("aria-label", val);
    });
    document.querySelectorAll("[data-i18n-option]").forEach(function (select) {
      var key = select.getAttribute("data-i18n-option");
      var list = resolve(dict, key);
      if (Array.isArray(list)) {
        Array.prototype.forEach.call(select.options, function (opt, i) {
          if (list[i] != null) opt.textContent = list[i];
        });
      }
    });
    document.querySelectorAll("[data-i18n-list]").forEach(function (container) {
      var key = container.getAttribute("data-i18n-list");
      var list = resolve(dict, key);
      if (Array.isArray(list)) {
        Array.prototype.forEach.call(container.children, function (li, i) {
          if (list[i] != null) li.textContent = list[i];
        });
      }
    });

    var metaTitle = resolve(dict, "meta.title");
    if (metaTitle) document.title = metaTitle;
    var metaDescEl = document.querySelector('meta[name="description"]');
    var metaDesc = resolve(dict, "meta.description");
    if (metaDescEl && metaDesc) metaDescEl.setAttribute("content", metaDesc);

    document.querySelectorAll(".lang-btn").forEach(function (btn) {
      btn.classList.toggle("active", btn.getAttribute("data-lang") === lang);
    });

    window.__vnsLang = lang;
    try { localStorage.setItem("vns-lang", lang); } catch (e) {}
  }

  window.VNS_I18N = { apply: applyLanguage, t: function (key) { return resolve(window.I18N[window.__vnsLang || "en"], key); } };

  document.addEventListener("DOMContentLoaded", function () {
    var savedLang = "en";
    try { savedLang = localStorage.getItem("vns-lang") || "en"; } catch (e) {}
    applyLanguage(savedLang);

    document.querySelectorAll(".lang-btn").forEach(function (btn) {
      btn.addEventListener("click", function () { applyLanguage(btn.getAttribute("data-lang")); });
    });

    function applyTheme(theme) {
      if (theme === "dark") document.documentElement.setAttribute("data-theme", "dark");
      else document.documentElement.removeAttribute("data-theme");
      try { localStorage.setItem("vns-theme", theme); } catch (e) {}
    }
    document.querySelectorAll(".theme-toggle").forEach(function (btn) {
      btn.addEventListener("click", function () {
        var isDark = document.documentElement.getAttribute("data-theme") === "dark";
        applyTheme(isDark ? "light" : "dark");
      });
    });
  });
})();
